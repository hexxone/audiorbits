// Class or object to return two values from rotatePoint
class Point {

    constructor(public x: f32, public y: f32) {}

}

// assumes the point is already relative to center
function rotatePoint(pX: f32, pY: f32, angle: f32): Point {
    const tmpCos: f32 = Math.cos(angle) as f32; // Cache cosine of angle
    const tmpSin: f32 = Math.sin(angle) as f32; // Cache sine of angle
    // Standard 2D rotation formulas:
    // x' = x*cos(theta) - y*sin(theta)
    // y' = y*cos(theta) + x*sin(theta)
    const rotX: f32 = pX * tmpCos - pY * tmpSin;
    const rotY: f32 = pY * tmpCos + pX * tmpSin;

    return new Point(rotX, rotY);
}

