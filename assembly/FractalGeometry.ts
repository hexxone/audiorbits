// Constants for noise generation
const NOISE_STX_BASE: f32 = -30.0;
const NOISE_STX_OFFS_MULTIPLIER: f32 = 240.0;
const NOISE_STX_SCALE_MULTIPLIER_A: f32 = 1.0;
const NOISE_STX_SCALE_MULTIPLIER_B: f32 = 6.0;

const NOISE_STY_BASE: f32 = -20.0;
const NOISE_STY_OFFS_MULTIPLIER: f32 = 320.0;
const NOISE_STY_SCALE_MULTIPLIER_A: f32 = 1.0;
const NOISE_STY_SCALE_MULTIPLIER_B: f32 = 5.0;

// Thresholds for conditional mixing and function choice in noise generation
const NOISE_TRIG_CHOICE_THRESHOLD: f32 = 0.4; // Determines using cos or sin initially
const NOISE_MIX_CHOICE_THRESHOLD_1: f32 = 0.8; // Determines if first mix occurs
const NOISE_MIX_TRIG_CHOICE_THRESHOLD: f32 = 0.5; // Determines cos/sin for mixed components
const NOISE_MIX_CHOICE_THRESHOLD_2: f32 = 0.7; // Determines if second mix occurs

/**
 * Mixes two values 'a' and 'b' based on an interpolator 'i'.
 * The fractional part of 'i' is used for linear interpolation.
 * @param {f32} a First value.
 * @param {f32} b Second value.
 * @param {f32} interpolator Interpolation factor.
 * @returns {f32} The mixed value.
 */
function mix(a: f32, b: f32, interpolator: f32): f32 { // Renamed i to interpolator
    return a + (b - a) * (interpolator % 1.0); // Using (interpolator % 1.0) ensures interpolator is in [0,1)
}

/**
 * Helper function for makeNoise. Generates a component of the noise.
 * It transforms input coordinates (stx, sty) based on offset (offS),
 * scale, and global random choices (choice1, choice2).
 * @param {f32} stx Input X coordinate.
 * @param {f32} sty Input Y coordinate.
 * @param {f32} offS Offset, typically derived from subset index.
 * @param {f32} scale Overall scale factor.
 * @param {f32} choice1_param Random choice parameter 1.
 * @param {f32} choice2_param Random choice parameter 2.
 * @returns {f32} A noise component value.
 */
function helpNoise(stx: f32, sty: f32, offS: f32, scale: f32, choice1_param: f32, choice2_param: f32): f32 {
    // Transform stx and sty based on input parameters and passed random choices
    // These transformations create a complex, somewhat chaotic input for the noise.
    stx = NOISE_STX_BASE + NOISE_STX_OFFS_MULTIPLIER * offS * choice1_param
        + (iabs(stx) / scale) * (NOISE_STX_SCALE_MULTIPLIER_A + NOISE_STX_SCALE_MULTIPLIER_B * choice2_param);
    sty = NOISE_STY_BASE + NOISE_STY_OFFS_MULTIPLIER * offS * choice2_param
        + (iabs(sty) / scale) * (NOISE_STY_SCALE_MULTIPLIER_A + NOISE_STY_SCALE_MULTIPLIER_B * choice1_param);

    // Return the magnitude of the transformed (stx, sty) vector.
    return isqrt(stx * stx + sty * sty);
}

/**
 * Generates a noise value based on input coordinates (stx, sty), an offset (offS), and scale.
 * This noise is used for Z-depth calculation. It involves multiple calls to helpNoise
 * and mixes their results using trigonometric functions and linear interpolation,
 * influenced by global random choices (choice1, choice2).
 * @param {f32} stx Input X coordinate.
 * @param {f32} sty Input Y coordinate.
 * @param {f32} offS Offset, typically derived from subset index.
 * @param {f32} scale Overall scale factor.
 * @param {f32} choice1_param Random choice parameter 1, passed from FractalGeometry.
 * @param {f32} choice2_param Random choice parameter 2, passed from FractalGeometry.
 * @returns {f32} The final noise value.
 */
function makeNoise(stx: f32, sty: f32, offS: f32, scale: f32, choice1_param: f32, choice2_param: f32): f32 {
    let noitmp: f32; // Temporary noise value, now local
    let noires: f32; // Resulting noise value, now local

    // Initial noise calculation
    noitmp = helpNoise(stx, sty, offS, scale, choice1_param, choice2_param);
    // Apply cosine or sine based on choice1_param
    noitmp = choice1_param < NOISE_TRIG_CHOICE_THRESHOLD ? icos(noitmp) : isin(noitmp);
    noires = noitmp; // Store as the current result

    // First conditional mix
    if (choice1_param < NOISE_MIX_CHOICE_THRESHOLD_1) {
        noitmp = helpNoise(stx, sty, offS, scale, choice1_param, choice2_param);
        // Apply cosine or sine based on choice1_param (using a different threshold pattern here)
        noitmp = choice1_param < NOISE_MIX_TRIG_CHOICE_THRESHOLD ? icos(noitmp) : isin(noitmp);
        noires = mix(noires, noitmp, choice1_param); // Mix current result with new temporary noise
    }

    // Second conditional mix, using choice2_param
    if (choice2_param < NOISE_MIX_CHOICE_THRESHOLD_2) {
        noitmp = helpNoise(stx, sty, offS, scale, choice1_param, choice2_param);
        // Apply cosine or sine based on choice2_param
        noitmp = choice2_param < NOISE_MIX_TRIG_CHOICE_THRESHOLD ? icos(noitmp) : isin(noitmp);
        noires = mix(noires, noitmp, choice2_param); // Mix current result with new temporary noise
    }

    return noires; // Return the final accumulated or mixed noise value
}

